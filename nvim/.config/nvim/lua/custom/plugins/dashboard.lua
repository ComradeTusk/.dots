  keys = {
    { '<leader>d', '<cmd>Dashboard<cr>', desc = 'Open DashBoard' },
  },
  config = function()
    require('dashboard').setup {
      theme = 'doom', -- "doom" (centered) | "hyper" (grid shortcuts)

      config = {
        header = cool,
        center = center,
        footer = footer,
      },

      -- Hide statusline, tabline and winbar on the dashboard buffer
      hide = {
        statusline = true,
        tabline = true,
        winbar = true,
      },
    }
  end,
}
